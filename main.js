function isIgnored(path, ignorePatterns) {
  const normalizedPath = path.replace(/\\/g, "/").replace(/^\/+/, "");
  const basename = normalizedPath.split("/").pop() || "";
  for (const pattern of ignorePatterns) {
    if (!pattern || pattern.trim() === "")
      continue;
    const cleanPattern = pattern.trim().replace(/\\/g, "/");
    if (cleanPattern === "._*" || cleanPattern.endsWith("/._*")) {
      if (basename.startsWith("._"))
        return true;
      continue;
    }
    if (cleanPattern.startsWith("*.")) {
      const ext = cleanPattern.slice(1);
      if (normalizedPath.endsWith(ext))
        return true;
      continue;
    }
    if (cleanPattern.endsWith("/**")) {
      const dirPrefix = cleanPattern.slice(0, -3).replace(/^\/+/, "").replace(/\/+$/, "");
      if (normalizedPath === dirPrefix || normalizedPath.startsWith(dirPrefix + "/") || normalizedPath.includes("/" + dirPrefix + "/")) {
        return true;
      }
      continue;
    }
    if (cleanPattern.endsWith("/")) {
      const dirName = cleanPattern.replace(/^\/+/, "").replace(/\/+$/, "");
      if (normalizedPath === dirName || normalizedPath.startsWith(dirName + "/") || normalizedPath.includes("/" + dirName + "/")) {
        return true;
      }
      continue;
    }
    const cleanExact = cleanPattern.replace(/^\/+/, "");
    if (normalizedPath === cleanExact || normalizedPath.endsWith("/" + cleanExact) || normalizedPath.startsWith(cleanExact + "/") || normalizedPath.includes("/" + cleanExact + "/")) {
      return true;
    }
  }
  return false;
}
